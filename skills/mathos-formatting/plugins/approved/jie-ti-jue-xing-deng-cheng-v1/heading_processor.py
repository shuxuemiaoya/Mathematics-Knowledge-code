def get_target_root() -> Path:
    sandbox = input().strip()
    return Path(sandbox)

def protect_blocks(text: str) -> str:
    return text

def restore_blocks(text: str) -> str:
    return text

def replace_in_file(path: Path) -> None:
    with open(path, 'r', encoding='utf-8') as f:
        lines = f.readlines()
    changed = False
    for line_num, (orig, new) in HEADING_REWRITES.items():
        idx = line_num - 1
        if idx >= len(lines):
            continue
        raw = lines[idx]
        stripped = raw.rstrip('\n\r')
        if stripped == orig:
            lines[idx] = new + raw[len(stripped):]
            changed = True
    if changed:
        with open(path, 'w', encoding='utf-8') as f:
            f.writelines(lines)

def main() -> None:
    root = get_target_root()
    skip_dirs = {'.git', 'node_modules', '.obsidian', '.trash', '__pycache__'}
    for md_path in root.rglob('*.md'):
        if any(part in skip_dirs for part in md_path.parts):
            continue
        replace_in_file(md_path)

if __name__ == "__main__":
    main()
